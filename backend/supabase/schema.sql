--  Replaces the legacy CSV datastore (backend/data/*.csv).
--
--  HOW TO USE
--    Dashboard > SQL Editor > New query > paste this whole file > Run.
--    Everything is idempotent (IF NOT EXISTS), so re-running is safe.
