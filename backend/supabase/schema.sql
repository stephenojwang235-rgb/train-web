--  WHAT THIS CREATES (9 tables)
--    users               disciple/member accounts   (was users.csv)
--    admins              staff logins               (was admins.csv)
--    visitors            "Plan a Visit" leads       (was visitors.csv)
--    sign_ins            login audit trail          (was sign_ins.csv)
--    messages            contact-form messages      (was messages.csv)
--    feedback            in-portal feedback         (was feedback.csv)
--    announcements       admin broadcasts          (was announcements.csv)
--    announcement_reads  per-disciple read state    (replaces user_ids JSON)
--    verification_codes  signup/portal OTP codes    (was verification_codes.csv)
